static inline uint8_t vga_inb(uint16_t port) {
    uint8_t ret;
    __asm__ volatile("inb %1, %0" : "=a"(ret) : "Nd"(port));
    return ret;
}

static inline void vga_outb(uint16_t port, uint8_t val) {
    __asm__ volatile("outb %0, %1" : : "a"(val), "Nd"(port));
}

static void vga_iodelay() {
    for (volatile int i = 0; i < 100; i++) vga_inb(0x80);
}

static void vga_crtc_write(uint8_t reg, uint8_t val) {
    vga_outb(0x3D4, reg);
    vga_iodelay();
    vga_outb(0x3D5, val);
    vga_iodelay();
}

static void vga_set_mode(int mode) {
    if (mode == VGA_GFX_MODE) {
        vga_outb(0x3D4, 0x11);
        vga_outb(0x3D5, vga_inb(0x3D5) & 0x7F);
        vga_iodelay();
        vga_outb(0x3C2, 0x63);
        vga_iodelay();
        vga_outb(0x3C4, 0x00); vga_outb(0x3C5, 0x03); vga_iodelay();
        vga_outb(0x3C4, 0x01); vga_outb(0x3C5, 0x01); vga_iodelay();
        vga_outb(0x3C4, 0x02); vga_outb(0x3C5, 0x0F); vga_iodelay();
        vga_outb(0x3C4, 0x04); vga_outb(0x3C5, 0x0E); vga_iodelay();
        vga_outb(0x3CE, 0x00); vga_outb(0x3CF, 0x00); vga_iodelay();
        vga_outb(0x3CE, 0x01); vga_outb(0x3CF, 0x00); vga_iodelay();
        vga_outb(0x3CE, 0x02); vga_outb(0x3CF, 0x00); vga_iodelay();
        vga_outb(0x3CE, 0x03); vga_outb(0x3CF, 0x00); vga_iodelay();
        vga_outb(0x3CE, 0x04); vga_outb(0x3CF, 0x00); vga_iodelay();
        vga_outb(0x3CE, 0x05); vga_outb(0x3CF, 0x40); vga_iodelay();
        vga_outb(0x3CE, 0x06); vga_outb(0x3CF, 0x05); vga_iodelay();
        vga_outb(0x3CE, 0x07); vga_outb(0x3CF, 0x0F); vga_iodelay();
        vga_outb(0x3CE, 0x08); vga_outb(0x3CF, 0xFF); vga_iodelay();
        for (int i = 0; i < 16; i++) {
            vga_inb(0x3DA);
            vga_outb(0x3C0, i);
            vga_outb(0x3C0, i);
            vga_iodelay();
        }
        vga_outb(0x3C0, 0x20);
        vga_iodelay();
        static const uint8_t crtc[] = {
            0x5F, 0x4F, 0x50, 0x82, 0x54, 0x80, 0xBF, 0x1F,
            0x00, 0x41, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x9C, 0x8E, 0x8F, 0x28, 0x1F, 0x96, 0xB9, 0xA3
        };
        for (int i = 0; i < 24; i++) vga_crtc_write(i, crtc[i]);
        vga_outb(0x3D4, 0x11);
        vga_outb(0x3D5, vga_inb(0x3D5) | 0x80);
        vga_iodelay();
    } else if (mode == VGA_TEXT_MODE) {
        vga_outb(0x3D4, 0x11);
        vga_outb(0x3D5, vga_inb(0x3D5) & 0x7F);
        vga_iodelay();
        vga_outb(0x3C2, 0x67);
        vga_iodelay();
        vga_outb(0x3C4, 0x00); vga_outb(0x3C5, 0x01); vga_iodelay();
        vga_outb(0x3C4, 0x01); vga_outb(0x3C5, 0x00); vga_iodelay();
        vga_outb(0x3C4, 0x02); vga_outb(0x3C5, 0x03); vga_iodelay();
        vga_outb(0x3C4, 0x03); vga_outb(0x3C5, 0x00); vga_iodelay();
        vga_outb(0x3C4, 0x04); vga_outb(0x3C5, 0x02); vga_iodelay();
        vga_outb(0x3CE, 0x00); vga_outb(0x3CF, 0x00); vga_iodelay();
        vga_outb(0x3CE, 0x01); vga_outb(0x3CF, 0x00); vga_iodelay();
        vga_outb(0x3CE, 0x02); vga_outb(0x3CF, 0x00); vga_iodelay();
        vga_outb(0x3CE, 0x03); vga_outb(0x3CF, 0x00); vga_iodelay();
        vga_outb(0x3CE, 0x04); vga_outb(0x3CF, 0x00); vga_iodelay();
        vga_outb(0x3CE, 0x05); vga_outb(0x3CF, 0x10); vga_iodelay();
        vga_outb(0x3CE, 0x06); vga_outb(0x3CF, 0x0E); vga_iodelay();
        vga_outb(0x3CE, 0x07); vga_outb(0x3CF, 0x00); vga_iodelay();
        vga_outb(0x3CE, 0x08); vga_outb(0x3CF, 0xFF); vga_iodelay();
        for (int i = 0; i < 16; i++) {
            vga_inb(0x3DA);
            vga_outb(0x3C0, i);
            vga_outb(0x3C0, i);
            vga_iodelay();
        }
        vga_outb(0x3C0, 0x20);
        vga_iodelay();
        static const uint8_t crtc[] = {
            0x5F, 0x4F, 0x50, 0x82, 0x55, 0x81, 0xBF, 0x1F,
            0x00, 0x4F, 0x0E, 0x0F, 0x00, 0x00, 0x00, 0x50,
            0x9C, 0x8E, 0x8F, 0x28, 0x1F, 0x96, 0xB9, 0xA3
        };
        for (int i = 0; i < 24; i++) vga_crtc_write(i, crtc[i]);
        vga_outb(0x3D4, 0x11);
        vga_outb(0x3D5, vga_inb(0x3D5) | 0x80);
        vga_iodelay();
    }
}

static uint8_t* vga_buffer = (uint8_t*)0xA0000;
static uint8_t vga_backbuffer[VGA_SIZE];
static int vga_graphic = 0;

static void vga_init() {
    vga_set_mode(VGA_TEXT_MODE);
    for (volatile int i = 0; i < 50000; i++) __asm__ volatile("nop");
    vga_set_mode(VGA_GFX_MODE);
    vga_graphic = 1;
    for (int i = 0; i < VGA_SIZE; i++) vga_buffer[i] = 0;
}

static void vga_exit() {
    vga_set_mode(VGA_TEXT_MODE);
    vga_graphic = 0;
    uint16_t* textbuf = (uint16_t*)0xB8000;
    for (int i = 0; i < 80*25; i++) textbuf[i] = 0x0720;
}

static void vga_vsync() {
    while (vga_inb(0x3DA) & 0x08);
    while (!(vga_inb(0x3DA) & 0x08));
}

static void vga_palette(uint8_t index, uint8_t r, uint8_t g, uint8_t b) {
    vga_outb(0x3C8, index);
    vga_outb(0x3C9, r & 0x3F);
    vga_outb(0x3C9, g & 0x3F);
    vga_outb(0x3C9, b & 0x3F);
}

static void vga_pixel(int x, int y, uint8_t c) {
    if (x < 0 || x >= VGA_WIDTH || y < 0 || y >= VGA_HEIGHT || !vga_graphic) return;
    vga_buffer[(uint32_t)y * VGA_WIDTH + (uint32_t)x] = c;
}

static void vga_buf_pixel(int x, int y, uint8_t c) {
    if (x < 0 || x >= VGA_WIDTH || y < 0 || y >= VGA_HEIGHT) return;
    vga_backbuffer[(uint32_t)y * VGA_WIDTH + (uint32_t)x] = c;
}

static void vga_clear(uint8_t c) {
    for (int i = 0; i < VGA_SIZE; i++) vga_backbuffer[i] = c;
}

static void vga_flip() {
    for (int i = 0; i < VGA_SIZE; i++) vga_buffer[i] = vga_backbuffer[i];
}

static void vga_rect(int x, int y, int w, int h, uint8_t fill, uint8_t border) {
    if(w <= 0 || h <= 0) return;
    for (int dx = 0; dx < w; dx++)
        for (int dy = 0; dy < h; dy++)
            vga_buf_pixel(x + dx, y + dy, fill);
    if (border != fill) {
        for (int dx = 0; dx < w; dx++) {
            vga_buf_pixel(x + dx, y, border);
            vga_buf_pixel(x + dx, y + h - 1, border);
        }
        for (int dy = 0; dy < h; dy++) {
            vga_buf_pixel(x, y + dy, border);
            vga_buf_pixel(x + w - 1, y + dy, border);
        }
    }
}

static void vga_line(int x1, int y1, int x2, int y2, uint8_t c) {
    int dx = x2 - x1, dy = y2 - y1;
    int steps = (dx > dy ? dx : dy);
    if (steps < 0) steps = -steps;
    if (steps == 0) steps = 1;
    for (int i = 0; i <= steps; i++) {
        vga_buf_pixel(x1 + (dx * i) / steps, y1 + (dy * i) / steps, c);
    }
}

static void vga_hline(int x, int y, int len, uint8_t c) {
    for(int i=0; i<len; i++) vga_buf_pixel(x+i, y, c);
}

static void vga_vline(int x, int y, int len, uint8_t c) {
    for(int i=0; i<len; i++) vga_buf_pixel(x, y+i, c);
}

