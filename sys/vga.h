static void vga_rus_char(int x, int y, unsigned char ch, uint8_t c) {
    const uint8_t* bm = 0;
    
    if(ch == 0xF0) {
        static const uint8_t Yo[7] = {0x20,0x00,0x78,0x80,0xF0,0x80,0x78};
        bm = Yo;
    } else if(ch == 0xF1) {
        static const uint8_t yo[7] = {0x20,0x00,0x70,0x88,0xF8,0x80,0x70};
        bm = yo;
    } else if(ch >= 0x80 && ch <= 0x9F) {
        bm = rus_font_upper[ch - 0x80];
    } else if(ch >= 0xA0 && ch <= 0xBF) {
        bm = rus_font_lower[ch - 0xA0];
    }
    
    if(bm) {
        for (int row = 0; row < 7; row++) {
            uint8_t mask = bm[row];
            if (mask & 0x80) vga_buf_pixel(x + 0, y + row, c);
            if (mask & 0x40) vga_buf_pixel(x + 1, y + row, c);
            if (mask & 0x20) vga_buf_pixel(x + 2, y + row, c);
            if (mask & 0x10) vga_buf_pixel(x + 3, y + row, c);
            if (mask & 0x08) vga_buf_pixel(x + 4, y + row, c);
        }
    }
}

static void vga_rus_text(int x, int y, const char* str, uint8_t c) {
    while(*str) {
        unsigned char ch = (unsigned char)*str;
        if(ch >= 0x80 || ch == 0xF0 || ch == 0xF1) {
            vga_rus_char(x, y, ch, c);
            x += FONT_W + 1;
        } else {
            vga_char(x, y, *str, c);
            x += FONT_W + 1;
        }
        str++;
    }
}

static void vga_window(int x, int y, int w, int h, uint8_t fill, uint8_t border, const char* title) {
    vga_rect(x, y, w, h, fill, border);
    if(title) {
        int tx = x + (w - (my_strlen(title) * (FONT_W+1))) / 2;
        vga_rect(x+1, y+1, w-2, FONT_H+2, border, border);
        vga_text(tx, y+2, title, VGA_WHITE);
    }
}

static void vga_cursor(int x, int y) {
    for(int r = 0; r < 9; r++) {
        for(int c = 0; c < r+1 && c < 7; c++) {
            vga_buf_pixel(x + c + 1, y + r + 1, VGA_BLACK);
            vga_buf_pixel(x + c, y + r, VGA_WHITE);
        }
    }
}

static void vga_delay(int count) {
    for (volatile int i = 0; i < count; i++) __asm__ volatile("nop");
}

